import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import process from 'node:process';

console.log('Memulai pemeriksaan tipe dan build Astro...');
execSync('npx vue-tsc --noEmit && npx astro check && npx astro build', { stdio: 'inherit' });

mkdirSync('dist', { recursive: true });
writeFileSync('dist/.nojekyll', '');

let fallbackGasUrl = '/api/gas';
let fallbackSiteKey = '';
let fallbackGoogleClientId = '';
try {
  const cfgRaw = readFileSync('public/config.js', 'utf8');
  const mGas = cfgRaw.match(/GAS_URL\s*:\s*['"]([^'"]*)['"]/);
  if (mGas && mGas[1]) fallbackGasUrl = mGas[1].trim();

  const mKey = cfgRaw.match(/RECAPTCHA_SITE_KEY\s*:\s*['"]([^'"]*)['"]/);
  if (mKey && mKey[1]) fallbackSiteKey = mKey[1].trim();
} catch {}

const gasUrl = (process.env.FRONTEND_GAS_URL || fallbackGasUrl || '/api/gas').trim();
const siteKey = (process.env.RECAPTCHA_SITE_KEY || fallbackSiteKey || '').trim();

writeFileSync(
  'dist/config.js',
  `// Auto-generated by build.mjs — jangan edit manual.\n` +
  `window.APP_CONFIG = {\n` +
  `  GAS_URL: ${JSON.stringify(gasUrl)},\n` +
  `  RECAPTCHA_SITE_KEY: ${JSON.stringify(siteKey)}\n` +
  `};\n`
);

console.log(`config.js: GAS_URL = ${gasUrl}`);
if (siteKey) {
  console.log('config.js: RECAPTCHA_SITE_KEY diisi dari environment build.');
} else {
  console.log('config.js: RECAPTCHA_SITE_KEY kosong — reCAPTCHA tidak aktif di frontend.');
}
console.log('Build selesai -> dist/');
